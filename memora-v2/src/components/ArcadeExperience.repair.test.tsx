import { afterEach, expect, it, vi } from 'vitest';
import { act, create, type ReactTestRenderer } from 'react-test-renderer';
import { contextualProcessFixture as unit } from '../test/contextualProcessFixture';
import { ArcadeExperience } from './ArcadeExperience';
import { MicroArcade } from './MicroArcade';
import { SentenceBuilderCard } from './SentenceBuilderCard';
import { ConversationPractice } from './ConversationPractice';
import { recordLearningActivity, readLearningActivities } from '../domain/learningActivity';
vi.mock('./MicroArcade', () => ({ MicroArcade: () => null }));
vi.mock('./ConversationPractice', () => ({ ConversationPractice: () => null }));
// Isolate repair, not the separately tested catalogue/exposure eligibility gates.
vi.mock('../domain/grammarArcadeRounds', () => ({ grammarArcadeRounds: () => [{}] }));
vi.mock('../domain/learningModes', () => ({ missingGrammarWords: () => [] }));
vi.mock('../services/directus', () => ({ loadAsset: vi.fn(async () => '') }));
vi.mock('../services/audio', () => ({ playEnglish: vi.fn(async () => ({ status: 'blocked', source: null })), playSpanish: vi.fn(), stopSpeech: vi.fn(), playSnap: vi.fn(), playMiss: vi.fn() }));
let tree: ReactTestRenderer;
afterEach(() => { if (tree) act(() => tree.unmount()); vi.unstubAllGlobals(); });
it('dos errores reales conservan padres y rescate único; el modelo no se convierte en acierto', async () => {
  const data = new Map<string, string>(), user = 'arcade-repair-isolated';
  vi.stubGlobal('localStorage', { getItem: (key: string) => data.get(key) ?? null, setItem: (key: string, value: string) => data.set(key, value), removeItem: (key: string) => data.delete(key) });
  vi.stubGlobal('window', { setTimeout, clearTimeout, dispatchEvent: vi.fn(), matchMedia: () => ({ matches: true }), getSelection: () => null });
  const seed = { unitId: unit.id, unitTitle: unit.title, contentVersion: unit.contentVersion!, activityId: 'test-eligibility', skill: 'ing', source: 'learner' as const, modality: 'choice' as const, prompt: unit.sentence.es, response: unit.sentence.en, expected: unit.sentence.en, correct: true, helped: true };
  recordLearningActivity(user, { ...seed, phase: 'construction' });
  recordLearningActivity(user, { ...seed, phase: 'dialogue' });
  await act(async () => { tree = create(<ArcadeExperience userId={user} units={[unit]} inspection={false} onExit={() => {}} />); });
  await act(async () => tree.root.findByType(MicroArcade).props.onMix());
  await act(async () => tree.root.findByType(MicroArcade).props.onUse());
  const attempts = () => readLearningActivities(user).filter((event) => event.activityId.startsWith('micro:'));
  const pick = (value: string) => tree.root.findByProps({ className: 'slot-options' }).findAllByType('button').find((node) => node.props.children === value)!.props.onClick();
  const stale = tree.root.findByType(SentenceBuilderCard).props;
  for (let index = 0; index < 2; index++) await act(async () => pick('playing.'));
  expect(stale.onAttempt('playing.', false, 0)).toBe(false);
  expect(attempts()).toHaveLength(2);
  expect(attempts()[1].parentAttemptId).toBe(attempts()[0].id);
  expect(tree.root.findByType(SentenceBuilderCard).props.needsModel).toBe(true);
  const accept = tree.root.findByType(SentenceBuilderCard).props.onAcceptModel;
  await act(async () => { accept(); accept(); });
  expect(attempts()).toHaveLength(3);
  expect(attempts()[2]).toMatchObject({ source: 'authored', correct: null, helped: true, expected: '', parentAttemptId: attempts()[1].id });
  expect(tree.root.findByType(SentenceBuilderCard).props.filledSlots).toBe(1);
  expect(tree.root.findByType(SentenceBuilderCard).props.vocabulary).toEqual(unit.words);
  expect(stale.onAttempt('I', true, 0)).toBe(false);
  await act(async () => pick('am'));
  await act(async () => pick('playing.'));
  await act(async () => tree.root.findByType(SentenceBuilderCard).props.onNext());
  expect(tree.root.findByType(ConversationPractice).props.initialHelped).toBe(true);
});
