it('solo usa el contrato exacto y no recicla una demostración de otro alumno, sentido o versión', () => {
  const original = JSON.stringify(word);
  expect(supportsCausalDiscovery(word)).toBe(true);
  expect(supportsCausalDiscovery({ ...word, scene: 'Otra historia.' })).toBe(false);
  expect(supportsCausalDiscovery({ ...word, imageUrl: 'another-author' })).toBe(false);
  recordCausalDiscovery(user, previewUnit, word); recordCausalDiscovery(user, previewUnit, word);
  expect(readLearningActivities(user)).toHaveLength(1);
  expect(hasCausalDiscovery('someone-else', previewUnit, word)).toBe(false);
  expect(hasCausalDiscovery(user, { ...previewUnit, contentVersion: 'other' }, word)).toBe(false);
  expect(hasCausalDiscovery(user, previewUnit, { ...word, associationVersion: (word.associationVersion ?? 0) + 1 })).toBe(false);
  expect(JSON.stringify(word)).toBe(original);
});
