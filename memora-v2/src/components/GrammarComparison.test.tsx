import { expect, it, vi } from 'vitest';
import { act, create } from 'react-test-renderer';
import { renderToStaticMarkup } from 'react-dom/server';
import { GrammarComparison } from './GrammarComparison';
import { piece, type LessonStep } from '../domain/grammarLesson';
import { playEnglish } from '../services/audio';
import { readGrammarAttempts } from '../domain/grammarMemory';
vi.mock('../services/audio', () => ({ playEnglish: vi.fn(async () => ({ status: 'unavailable', source: null })), stopSpeech: vi.fn() }));

const first: LessonStep = { caption: 'Yo.', es: [piece('YO', 'subject')], en: [piece('I', 'subject')] };
const next: LessonStep = { caption: 'Yo estoy.', es: [piece('YO ', 'subject'), piece('ESTOY', 'auxiliary')], en: [piece('I ', 'subject'), piece('AM', 'auxiliary')] };
it('mantiene el modelo completo y señala el cambio con texto, no solo color', () => {
  const html = renderToStaticMarkup(<GrammarComparison step={next} previous={first} />);
  expect(html).toContain('coach-subject">I ');
  expect(html).toContain('coach-auxiliary comparison-changed">AM');
  expect(html).toContain('Repetir cambio');
  expect(html).toContain('ESPAÑOL'); expect(html).toContain('INGLÉS');
});
it('demuestra I + am solo cuando cambia la forma, no el significado ni la acción', () => {
  const es = [piece('Estoy jugando', 'auxiliary')];
  const previous = { caption: '', es, en: [piece('I ', 'subject'), piece('am ', 'auxiliary'), piece('playing', 'verb')] };
  const step = { caption: '', es, en: [piece("I'm ", 'auxiliary'), piece('playing', 'verb')] };
  const html = renderToStaticMarkup(<GrammarComparison step={step} previous={previous} />);
  expect(html).toContain('comparison-contraction');
  expect(html).toContain('comparison-source');
  expect(html).toContain('aria-hidden="true"');
  expect(html).toContain('coach-subject">I</span>');
  expect(renderToStaticMarkup(<GrammarComparison step={{ ...step, es: [piece('Estoy comiendo', 'auxiliary')] }} previous={previous} />)).not.toContain('comparison-contraction');
  expect(renderToStaticMarkup(<GrammarComparison step={{ ...step, en: [piece("I'm ", 'auxiliary'), piece('eating', 'verb')] }} previous={previous} />)).not.toContain('comparison-contraction');
});
it('repite únicamente la demostración y conserva el modelo completo', () => {
  const advance = vi.fn();
  let tree!: ReturnType<typeof create>;
  act(() => { tree = create(<section onClick={advance}><GrammarComparison step={next} previous={first} /></section>); });
  const replay = tree.root.findByType('button');
  const stopPropagation = vi.fn();
  act(() => { replay.props.onClick({ stopPropagation }); });
  expect(stopPropagation).toHaveBeenCalledOnce();
  expect(advance).not.toHaveBeenCalled();
  expect(tree.root.findAllByProps({ lang: 'en' })[0].children.map((node: any) => node.children?.join('')).join('')).toBe('I AM');
  act(() => { tree.unmount(); });
});
it('no revela inglés ni compara contra un modelo que todavía estaba oculto', () => {
  const hidden = { ...first, hideEnglish: true };
  expect(renderToStaticMarkup(<GrammarComparison step={hidden} />)).not.toContain('INGLÉS');
  expect(renderToStaticMarkup(<GrammarComparison step={next} previous={hidden} />)).not.toContain('comparison-changed');
  expect(renderToStaticMarkup(<GrammarComparison step={next} previous={next} />)).not.toContain('Cambia aquí:');
});

it('el laboratorio general revierte las dos caras del ejemplo preparado, sin sumar respuestas ni bloquear por voz', async () => {
  vi.mocked(playEnglish).mockClear();
  const text = (node: any): string => typeof node === 'string' ? node : Array.isArray(node) ? node.map(text).join(' ') : node?.children ? text(node.children) : '';
  let tree!: ReturnType<typeof create>;
  await act(async () => { tree = create(<GrammarComparison interactive step={next} previous={first} />); });
  expect(text(tree.toJSON())).toContain('ESTOY');
  expect(tree.root.findAllByType('input')).toHaveLength(0);
  await act(async () => tree.root.findByProps({ 'aria-pressed': false }).props.onClick());
  expect(text(tree.toJSON())).not.toContain('ESTOY');
  expect(text(tree.toJSON()).replace(/\s+\./g, '.')).toContain('Yo.');
  expect(playEnglish).not.toHaveBeenCalled();
  await act(async () => tree.root.findByProps({ 'aria-label': 'Escuchar el ejemplo visible' }).props.onClick());
  expect(playEnglish).toHaveBeenLastCalledWith('I', undefined, true, expect.any(Function));
  expect(text(tree.toJSON())).toContain('Audio no disponible');
  await act(async () => tree.root.findByProps({ 'aria-pressed': true }).props.onClick());
  expect(text(tree.toJSON())).toContain('ESTOY');
  expect(playEnglish).toHaveBeenCalledOnce();
  await act(async () => tree.root.findByProps({ 'aria-label': 'Escuchar el ejemplo visible' }).props.onClick());
  expect(playEnglish).toHaveBeenLastCalledWith('I AM', undefined, true, expect.any(Function));
  expect(readGrammarAttempts('comparison-isolated')).toEqual([]);
  act(() => tree.unmount());
});
it('conecta el papel explícito español/inglés al tocar sin inventar equivalencias ni evaluar', async () => {
  vi.mocked(playEnglish).mockClear();
  let tree!: ReturnType<typeof create>;
  await act(async () => { tree = create(<GrammarComparison connectPieces step={next} previous={first} />); });
  const control = tree.root.findByProps({ 'aria-label': 'Relacionar AM con el español' });
  await act(async () => control.props.onClick());
  const link = tree.root.findByProps({ className: 'comparison-piece-link has-focus' });
  expect(link.findByProps({ lang: 'es' }).children).toEqual(['ESTOY']);
  expect(link.findByProps({ lang: 'en' }).children).toEqual(['AM']);
  expect(control.props['aria-pressed']).toBe(true);
  expect(playEnglish).not.toHaveBeenCalled();
  await act(async () => tree.root.findByProps({ 'aria-label': 'Relacionar YO con el inglés' }).props.onClick());
  expect(tree.root.findByProps({ 'aria-label': 'Relacionar I con el español' }).props['aria-pressed']).toBe(true);
  expect(playEnglish).not.toHaveBeenCalled();
  expect(readGrammarAttempts('comparison-isolated')).toEqual([]);
  act(() => tree.unmount());
  act(() => { tree = create(<GrammarComparison connectPieces step={{ ...first, hideEnglish: true }} />); });
  expect(tree.root.findAllByType('button')).toHaveLength(0);
  act(() => tree.unmount());
});
it('conecta también el bloque de contexto completo, sin equiparar una preposición aislada con todo el español', async () => {
  const step = { caption: 'Indica el lugar.', es: [piece('en mi escritorio', 'context')], en: [piece('at my desk', 'context')] };
  let tree!: ReturnType<typeof create>;
  await act(async () => { tree = create(<GrammarComparison connectPieces step={step} />); });
  await act(async () => tree.root.findByProps({ 'aria-label': 'Relacionar en mi escritorio con el inglés' }).props.onClick());
  const bridge = tree.root.findByProps({ className: 'comparison-piece-link has-focus' });
  expect(bridge.findByProps({ lang: 'en' }).children).toEqual(['at my desk']);
  expect(bridge.findByProps({ lang: 'es' }).children).toEqual(['en mi escritorio']);
  act(() => tree.unmount());
});
