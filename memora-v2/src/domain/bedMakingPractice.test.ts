import { expect, it } from 'vitest';
import { reviewUnits } from '../preview/previewUnit';
import { bedMakingLesson, bedMakingSkill, preparedBedMakingPractice } from './bedMakingPractice';
import { grammarChecksForExperience, validateGrammarLesson } from './grammarLesson';
import { grammarTricks, missingTrickWords, trickStop } from './journeyTricks';
import { validateUnit } from './unit';
import type { WordMemory } from './memory';
const source = reviewUnits.find((unit) => unit.id === 'm1-bedroom-bed')!;
const memories = source.words.map((word) => ({ key: word.en.toLowerCase(), correct: 1, word })) as WordMemory[];
it('enseña MY BED, uso MAKE MY BED y cambio MAKE→MAKING antes de exigir el mensaje corto', () => {
  const before = JSON.stringify(source); const lesson = bedMakingLesson(source, 'ing')!;
  expect(() => validateGrammarLesson(lesson)).not.toThrow();
  const prepared = preparedBedMakingPractice(source, 'ing', memories)!;
  expect(() => validateUnit(prepared.unit)).not.toThrow();
  expect(prepared.lesson.id).toBe(bedMakingSkill);
  expect(lesson.steps).toHaveLength(6);
  expect(lesson.steps[2].en.map((part) => part.text).join('')).toBe('MY BED');
  expect(lesson.steps[3].en.map((part) => part.text).join('')).toBe('make my bed');
  expect(lesson.steps[4].caption).toContain('MAKE → MAKING');
  expect(prepared.unit.sentence.en).toBe('I am making my bed.');
  expect(grammarChecksForExperience(lesson, ['I am making my bed.'], [prepared.unit.sentence.en]).map((check) => check.id)).toEqual(['bed-meaning-v1']);
  const assessedEnglish = [prepared.unit.sentence.en, ...lesson.checks.flatMap((check) => check.answers)].join(' ');
  expect(assessedEnglish).not.toMatch(/with|desk|phone|makeing/iu);
  expect([3, 4, 2, 1, 0].map((index) => lesson.checks[0].ordering![index].text).join(' ')).toBe('I AM MAKING MY BED');
  expect(prepared.unit.words).toEqual(source.words); expect(prepared.unit.contentVersion).toBe(source.contentVersion);
  expect(prepared.unit.grammarContinuation).toBeUndefined();
  expect(JSON.stringify(source)).toBe(before);
});
it('requiere los tres sentidos/versiones y no reemplaza otros autores o continuaciones pendientes', () => {
  expect(grammarTricks(source)[0]).toMatchObject({ skill: bedMakingSkill, vocabulary: ['make', 'bed', 'pillow'] });
  expect(missingTrickWords(trickStop(source, grammarTricks(source)[0]), [])).toEqual(['make', 'bed', 'pillow']);
  expect(preparedBedMakingPractice(source, 'ing', memories.slice(0, 2))).toBeNull();
  expect(preparedBedMakingPractice(source, 'ing', memories.map((memory) => ({ ...memory, word: { ...memory.word, es: 'otro sentido' } })))).toBeNull();
  expect(preparedBedMakingPractice({ ...source, words: source.words.map((word) => ({ ...word, associationVersion: (word.associationVersion ?? 1) + 1 })) }, 'ing', memories)).toBeNull();
  expect(bedMakingLesson({ ...source, id: 'otra-unidad' }, 'ing')).toBeNull();
  expect(bedMakingLesson({ ...source, grammar: [{ ...source.grammar[0], lesson: { ...source.grammar[0].lesson!, id: 'otro-autor' } }] }, 'ing')).toBeNull();
  expect(bedMakingLesson({ ...source, grammar: [{ ...source.grammar[0], english: 'makeing' }] }, 'ing')).toBeNull();
  expect(bedMakingLesson({ ...source, grammarContinuation: { status: 'needs_review', formId: 'ing', vocabulary: ['make'], grammarSkills: [] } }, 'ing')).toBeNull();
});
